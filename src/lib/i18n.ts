const DICTS: Record<Lang, Dict> = { en, "zh-TW": zhTW, "zh-CN": zhCN };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>) {
  let out = DICTS[lang]?.[key] ?? DICTS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
}

export function formatDateIn(lang: Lang, d: Date) {
  const locale = lang === "en" ? "en-HK" : lang === "zh-CN" ? "zh-CN" : "zh-HK";
  return d.toLocaleDateString(locale, { month: "long", day: "numeric" });
}

/** Reads the saved system language and re-renders when settings change. */
export function useLang() {
  const [lang, setLang] = useState<Lang>("zh-TW");
  useEffect(() => {
    const sync = () => setLang(getState().settings.language ?? "zh-TW");
    sync();
    window.addEventListener("wq-updated", sync);
    window.addEventListener("focus", sync);
    return () => {
      window.removeEventListener("wq-updated", sync);
      window.removeEventListener("focus", sync);
    };
  }, []);
  const t = (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars);
  return { lang, t, fmtDate: (d: Date) => formatDateIn(lang, d) };
}
